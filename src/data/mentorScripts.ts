const GENERIC_FOLLOWUPS = [
  "Расскажите об этом чуть подробнее?",
  "Что вы сами думаете по этому поводу?",
  "Как это связано с вашей целью?",
  "Что было бы небольшим, но реальным шагом здесь?",
];

export function containsCrisisSignal(text: string): boolean {
  const lower = text.toLowerCase();
  return CRISIS_KEYWORDS.some((kw) => lower.includes(kw));
}

let followupCursor = 0;

export function mentorReply(userText: string): string {
  if (containsCrisisSignal(userText)) {
    return CRISIS_RESPONSE;
  }
  const reply = GENERIC_FOLLOWUPS[followupCursor % GENERIC_FOLLOWUPS.length];
  followupCursor += 1;
  return reply;
}
